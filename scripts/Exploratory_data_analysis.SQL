--------------------------------------------------
--MAGNITUDE ANALYSIS
--------------------------------------------------
-- Find total customers by countries
SELECT country, COUNT(customer_id) AS tot_cust_per_country
FROM gold.dim_customers
GROUP BY country
ORDER BY tot_cust_per_country DESC;
-- Find total customers by gender
SELECT gender, COUNT(customer_id) AS tot_cust_per_gen
FROM gold.dim_customers
GROUP BY gender
ORDER BY tot_cust_per_gen DESC;
-- Find total products by category
SELECT category_name, COUNT(DISTINCT product_id) AS tot_prod_per_cat
FROM gold.dim_products
GROUP BY category_name
ORDER BY tot_prod_per_cat DESC;
-- What is the average costs in each category?
SELECT category_name, 
AVG(product_cost) AS avg_cst_per_cat
FROM gold.dim_products
GROUP BY category_name
ORDER BY avg_cst_per_cat DESC;
-- What is the total revenue generated for each category?
SELECT
	dp.category_name, SUM(fs.sales) AS tot_revenue_per_cat
FROM gold.fact_sales fs
LEFT JOIN gold.dim_products dp  
ON fs.product_key=dp.product_key
GROUP BY dp.category_name
ORDER BY tot_revenue_per_cat;
-- Find total revenue is generated by each customer
SELECT
	cu.customer_key,
	cu.first_name,
	cu.last_name,
	SUM(fs.sales) AS tot_revenue_per_custom
FROM gold.fact_sales fs
LEFT JOIN gold.dim_customers cu 
ON fs.customer_key=cu.customer_key
GROUP BY cu.first_name, cu.last_name, cu.customer_key
ORDER BY tot_revenue_per_custom DESC;
-- What is the distribution of sold items across countries?
SELECT 
	cu.country,
	SUM(fs.quantity) AS tot_revenue_per_country
FROM gold.fact_sales AS fs
LEFT JOIN gold.dim_customers AS cu
ON fs.customer_key=cu.customer_key
GROUP BY cu.country
ORDER BY tot_revenue_per_country DESC;
--------------------------------------------------
--RANKING ANALYSIS
--------------------------------------------------
--which 5 products generate the highest revenue
SELECT TOP (5)
p.product_name,
SUM(s.sales) AS tot_revenue_per_custom
FROM gold.fact_sales s
LEFT JOIN gold.dim_products p
ON p.product_key=s.product_key
GROUP BY p.product_name
ORDER BY tot_revenue_per_custom DESC;

--Alternate:

SELECT  
*
FROM (SELECT 
	p.product_name,
	SUM(s.sales) AS tot_revenue_per_custom,
	DENSE_RANK() OVER(ORDER BY SUM(s.sales) ) AS rank_products
	FROM gold.fact_sales s
	LEFT JOIN gold.dim_products p
	ON p.product_key=s.product_key
	GROUP BY p.product_name
)t WHERE rank_products<=5;

--what are the 5 worst-performing products in terms of sales 
SELECT  
*
FROM (SELECT 
	p.product_name,
	SUM(s.sales) AS tot_revenue_per_custom,
	ROW_NUMBER() OVER(ORDER BY SUM(s.sales) ASC) AS rank_products
	FROM gold.fact_sales s
	LEFT JOIN gold.dim_products p
	ON p.product_key=s.product_key
	GROUP BY p.product_name
)t WHERE rank_products<=5;

--find top 10 customers who have generated highest revenue
SELECT TOP 10
	cu.customer_key,
	cu.first_name,
	cu.last_name,
	SUM(fs.sales) AS tot_revenue_per_custom
FROM gold.fact_sales fs
LEFT JOIN gold.dim_customers cu 
ON fs.customer_key=cu.customer_key
GROUP BY 
	cu.first_name, 
	cu.last_name, 
	cu.customer_key	
ORDER BY tot_revenue_per_custom DESC;
--3 customers with fewest orders placed
SELECT TOP 3
	cu.customer_key,
	cu.first_name,
	cu.last_name,
	COUNT(DISTINCT order_number) AS ord_placed
FROM gold.fact_sales fs
LEFT JOIN gold.dim_customers cu 
ON fs.customer_key=cu.customer_key
GROUP BY 
	cu.first_name, 
	cu.last_name, 
	cu.customer_key	
ORDER BY ord_placed ASC;
