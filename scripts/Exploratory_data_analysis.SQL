--DATE EXPLORATION
--------------------------------------------------
--find the date of first and last order and how many years of sales are available

SELECT 
	MIN(order_date) AS First_order,
	MAX(order_date) AS Last_order,
	DATEDIFF(MONTH, MIN(order_date),MAX(order_date)) AS order_range_months
FROM gold.fact_sales;

--find youngest and the oldest customer
SELECT 
	MIN(birthdate) AS oldest_birthdate,
	DATEDIFF(YEAR, MIN(birthdate), GETDATE()) AS oldest_customer,
	MAX(birthdate) AS youngest_birthdate,
	DATEDIFF(YEAR, MAX(birthdate), GETDATE()) AS youngest_customer
FROM gold.dim_customers; 
	
